//! Span conformance corpus.
//!
//! Julia's record pairs QNR's results with the scanner's units on kind and code, in order
//! (EXR-8 B5b; `engine/ts_record.rs`), so a document where the two disagree on which spans
//! exist still gets a record: a unit QNR did not run has no record cell and presents as
//! its source, and a result with no unit is dropped. The unit tests there run these four
//! documents through `attach_record`. This file keeps the measurement of the disagreement
//! itself. `tests/fixtures/span-conformance/`
//! holds one document per question, and `qnr-spans.json` the `julia` spans QNR actually
//! evaluated in each (generated by `scripts/exr-julia-span-conformance/run-qnr.jl`,
//! which needs Julia; not run in CI, rerun it when QNR's span handling changes).
//!
//! Julia's view of the scanner's spans leaves out the ones in the front matter
//! (`in_front_matter`), because QNR never evaluates those. Every document then either
//! agrees with QNR or is listed in `EXPECTED` with its classification.

#![cfg(not(target_arch = "wasm32"))]

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use quarto_core::engine::units::{Unit, line_at, scan_units};

fn corpus() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/span-conformance")
}

/// `(line, code)` for each `julia` span the scanner claims, front matter included.
fn scanner_spans(doc: &str) -> Vec<(usize, String, bool)> {
    scan_units(doc)
        .iter()
        .filter_map(|u| match u {
            Unit::Inline(i) if i.lang.eq_ignore_ascii_case("julia") => {
                Some((line_at(doc, i.start), i.code.clone(), i.in_front_matter))
            }
            _ => None,
        })
        .collect()
}

fn qnr_spans() -> std::collections::BTreeMap<String, Vec<(usize, String)>> {
    let text = std::fs::read_to_string(corpus().join("qnr-spans.json")).unwrap();
    let v: serde_json::Value = serde_json::from_str(&text).unwrap();
    v.as_object()
        .unwrap()
        .iter()
        .map(|(name, spans)| {
            let spans = spans
                .as_array()
                .unwrap()
                .iter()
                .map(|s| {
                    (
                        s["line"].as_u64().unwrap() as usize,
                        s["code"].as_str().unwrap().to_string(),
                    )
                })
                .collect();
            (name.clone(), spans)
        })
        .collect()
}

/// A documented disagreement between the scanner and QNR.
struct Difference {
    doc: &'static str,
    /// Codes the scanner claims (outside the front matter) and QNR does not run.
    scanner_only: &'static [&'static str],
    /// Codes QNR runs and the scanner does not claim.
    qnr_only: &'static [&'static str],
    /// The classification and why.
    why: &'static str,
}

const EXPECTED: &[Difference] = &[
    Difference {
        doc: "indented-code.qmd",
        scanner_only: &["1 + 1"],
        qnr_only: &[],
        why: "HANDLED BY ALIGNMENT (found by this corpus; B5b, 2026-11-01): the scanner does not know \
              indented code blocks, so a span inside one is claimed, while QNR's CommonMark \
              parse leaves it as code. The span has no record cell and stays as written. FIX SCANNER would need block \
              structure the line scanner does not have (fences are handled, indented code \
              and list or quote nesting are not), and the scanner is shared with knitr and \
              jupyter.",
    },
    Difference {
        doc: "escaped-backtick.qmd",
        scanner_only: &["1 + 1\\"],
        qnr_only: &[],
        why: "HANDLED BY ALIGNMENT (found by this corpus; B5b, 2026-11-01): the scanner only needs a \
              non-backtick before the opening backtick, so a backslash-escaped opening \
              backtick still starts a span (code `1 + 1\\`), while CommonMark and QNR treat it \
              as literal text. The span has no record cell and stays as written. The rejected alternative was FIX SCANNER (skip an \
              opening backtick preceded by an odd number of backslashes), but the scanner \
              is shared with knitr and jupyter and feeds unit ids and hashes, so that is \
              shared code, not a Julia-only change.",
    },
    Difference {
        doc: "double-backtick.qmd",
        scanner_only: &[],
        qnr_only: &["1 + 1"],
        why: "HANDLED BY ALIGNMENT (B5b): QNR runs any CommonMark code span that starts `{lang} `, \
              the scanner's regex needs a single backtick. The result has no unit and is \
              dropped; the span stays as written. Widening the scanner would change the \
              spans knitr and jupyter see too.",
    },
    Difference {
        doc: "tab-separator.qmd",
        scanner_only: &["1 + 1"],
        qnr_only: &[],
        why: "HANDLED BY ALIGNMENT (B5b): the scanner takes a tab after the language token, QNR's \
              marker is a literal space and leaves the span as text. The span has no record \
              cell and stays as written.",
    },
];

#[test]
fn every_corpus_document_has_qnr_output() {
    let qnr = qnr_spans();
    let mut docs: Vec<String> = std::fs::read_dir(corpus())
        .unwrap()
        .filter_map(|e| e.ok()?.file_name().into_string().ok())
        .filter(|n| n.ends_with(".qmd"))
        .collect();
    docs.sort();
    let recorded: Vec<&String> = qnr.keys().collect();
    assert_eq!(
        docs.iter().collect::<Vec<_>>(),
        recorded,
        "rerun scripts/exr-julia-span-conformance/run-qnr.jl"
    );
}

#[test]
fn scanner_and_qnr_spans_agree_except_where_classified() {
    let qnr = qnr_spans();
    for (doc, qnr_spans) in &qnr {
        let text = std::fs::read_to_string(corpus().join(doc)).unwrap();
        let ours: BTreeSet<(usize, String)> = scanner_spans(&text)
            .into_iter()
            .filter(|(_, _, fm)| !fm)
            .map(|(l, c, _)| (l, c))
            .collect();
        let theirs: BTreeSet<(usize, String)> = qnr_spans.iter().cloned().collect();
        let codes = |s: BTreeSet<(usize, String)>| -> Vec<String> {
            s.into_iter().map(|(_, c)| c).collect()
        };
        let scanner_only = codes(ours.difference(&theirs).cloned().collect());
        let qnr_only = codes(theirs.difference(&ours).cloned().collect());
        match EXPECTED.iter().find(|d| d.doc == doc) {
            None => assert!(
                scanner_only.is_empty() && qnr_only.is_empty(),
                "{doc}: unclassified difference; scanner only {scanner_only:?}, QNR only \
                 {qnr_only:?}"
            ),
            Some(d) => {
                assert_eq!(scanner_only, d.scanner_only, "{doc}: {}", d.why);
                assert_eq!(qnr_only, d.qnr_only, "{doc}: {}", d.why);
            }
        }
    }
}

#[test]
fn front_matter_span_is_claimed_and_flagged() {
    // The scanner counts the title's span; only `in_front_matter` lets Julia's view
    // leave it out. Without the flag this document would be a count mismatch.
    let text = std::fs::read_to_string(corpus().join("front-matter.qmd")).unwrap();
    let spans = scanner_spans(&text);
    assert_eq!(spans.len(), 2);
    assert!(spans[0].2, "the title span is in the front matter");
    assert!(!spans[1].2);
}

#[test]
fn html_comment_span_is_ignored_by_both() {
    let text = std::fs::read_to_string(corpus().join("html-comment.qmd")).unwrap();
    assert_eq!(scanner_spans(&text).len(), 1);
    assert_eq!(qnr_spans()["html-comment.qmd"].len(), 1);
}
