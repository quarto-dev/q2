#!/usr/bin/env python3
"""Generate crates/quarto-highlight/src/pandoc_languages_table.rs.

The table lists the syntaxes Pandoc's highlighter (skylighting) knows, so
q2 can wrap code blocks in `div.sourceCode` exactly when Quarto 1 does
(GH #1079). Quarto 1 pins Pandoc 3.10, which requires skylighting-core
>= 0.14.7 && < 0.15; Quarto 1 also passes its own syntax definitions
(src/resources/pandoc/syntax-definitions/), which replace same-named
skylighting syntaxes.

Usage:
    python3 gen_pandoc_languages.py SKYLIGHTING_XML_DIR QUARTO_SYNTAX_DIR > ../src/pandoc_languages_table.rs

where SKYLIGHTING_XML_DIR is `skylighting-core/xml` from the skylighting
repository at tag 0.14.7, and QUARTO_SYNTAX_DIR is
`external-sources/quarto-cli/src/resources/pandoc/syntax-definitions`.
"""

import html
import os
import re
import sys

ATTR = re.compile(r"""(\w+)\s*=\s*(?:"([^"]*)"|'([^']*)')""")


def parse(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    m = re.search(r"<language\s([^>]*)>", text, re.S)
    if not m:
        raise SystemExit(f"no <language> element in {path}")
    attrs = {k: (dq if dq else sq) for k, dq, sq in ATTR.findall(m.group(1))}
    if "name" not in attrs:
        raise SystemExit(f"<language> without name in {path}")
    # skylighting's `pathToLangName`: file stem, lowercased, '-' removed.
    stem = os.path.basename(path)[: -len(".xml")]
    short = stem.replace("-", "").lower()
    globs = [g for g in html.unescape(attrs.get("extensions", "")).split(";") if g]
    return html.unescape(attrs["name"]), short, globs


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main(dirs):
    syntaxes = {}
    for d in dirs:
        for fn in sorted(os.listdir(d)):
            if fn.endswith(".xml"):
                name, short, globs = parse(os.path.join(d, fn))
                # Later directories replace by (case-insensitive) name, like
                # Pandoc's `--syntax-definition`.
                syntaxes[name.lower()] = (name, short, globs)
    out = [
        "// @generated by crates/quarto-highlight/scripts/gen_pandoc_languages.py",
        "// from skylighting-core 0.14.7 (Pandoc 3.10) plus Quarto 1's syntax",
        "// definitions. Do not edit by hand; re-run the script instead.",
        "",
        "/// One syntax known to Pandoc's highlighter: full name, short name",
        "/// (the definition's file stem) and file-name globs.",
        "pub(crate) struct PandocSyntax {",
        "    pub(crate) name: &'static str,",
        "    pub(crate) short: &'static str,",
        "    pub(crate) globs: &'static [&'static str],",
        "}",
        "",
        "pub(crate) static PANDOC_SYNTAXES: &[PandocSyntax] = &[",
    ]
    for name, short, globs in sorted(syntaxes.values(), key=lambda t: t[1]):
        g = ", ".join(rust_str(x) for x in globs)
        out.append(
            f"    PandocSyntax {{ name: {rust_str(name)}, short: {rust_str(short)}, globs: &[{g}] }},"
        )
    out.append("];")
    print("\n".join(out))


if __name__ == "__main__":
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    main(sys.argv[1:])
