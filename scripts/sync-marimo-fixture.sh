#!/usr/bin/env bash
# Re-sync crates/quarto-core/tests/fixtures/extensions/marimo from a quarto-marimo
# checkout (the fork's q2/node-port branch). Builds the bundle first, so the
# committed engine bundle is always a fresh build of the recorded commit.
#
#   scripts/sync-marimo-fixture.sh [path-to-quarto-marimo]   (default ~/src/quarto-marimo)
#
# Writes FIXTURE-SOURCE beside the extension: the source commit plus a sha256 per
# synced file. marimo_fixture_fresh (tests/integration) checks those hashes, and
# rebuilds from QUARTO_MARIMO_SRC when set.
set -euo pipefail
src="$(cd "${1:-$HOME/src/quarto-marimo}" && pwd)"
here="$(cd "$(dirname "$0")/.." && pwd)"
dest="$here/crates/quarto-core/tests/fixtures/extensions/marimo/_extensions/marimo"

[ -z "$(git -C "$src" status --porcelain --untracked-files=no)" ] || { echo "dirty: $src" >&2; exit 1; }
(cd "$src" && npm run build >/dev/null)

rm -rf "$dest"
mkdir -p "$dest/assets"
ver="$(sed -n 's/^version: *"\{0,1\}\([^"# ]*\).*/\1/p' "$src/_extensions/marimo/_extension.yml")"
cp "$src/_extensions/marimo/_extension.yml" "$dest/"
cp "$src/dist/marimo-engine-v$ver.js" "$dest/marimo-engine.js"
cp "$src/dist/browser-v$ver.js" "$src/dist/islands-bridge-v$ver.css" "$dest/assets/"
# Tracked python sources only (no __pycache__).
git -C "$src" ls-files -z _extensions/marimo/python | while IFS= read -r -d '' f; do
  mkdir -p "$dest/$(dirname "${f#_extensions/marimo/}")"
  cp "$src/$f" "$dest/${f#_extensions/marimo/}"
done

{
  echo "# Generated by scripts/sync-marimo-fixture.sh; do not edit."
  echo "source: gordonwoodhull/quarto-marimo $(git -C "$src" rev-parse HEAD)"
  echo "version: $ver"
  (cd "$dest" && find . -type f ! -name FIXTURE-SOURCE | LC_ALL=C sort | while read -r f; do
    echo "$(shasum -a 256 "$f" | cut -d' ' -f1)  ${f#./}"; done)
} > "$dest/FIXTURE-SOURCE"
echo "synced marimo fixture v$ver"
