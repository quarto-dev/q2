#!/usr/bin/env bash
# Render the Homebrew formula (Formula/q2.rb in quarto-dev/homebrew-q2)
# for a stable release, from the release's combined checksums file:
#
#   scripts/homebrew-formula.sh 0.42.0 checksums.sha256 > q2.rb
#
# Run by the `homebrew-tap` job in .github/workflows/release-pipeline.yml.
# Tests: crates/quarto/tests/integration/homebrew_formula.rs.

set -euo pipefail

die() {
  echo "homebrew-formula.sh: $*" >&2
  exit 1
}

[ $# -eq 2 ] || die "usage: homebrew-formula.sh <version> <checksums.sha256>"
version=$1
checksums=$2
[[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] ||
  die "version must be a bare stable X.Y.Z (got '$version')"
[ -r "$checksums" ] || die "cannot read $checksums"

# Print one archive's url and sha256 lines, or fail.
archive() {
  local file="q2-${version}-$1.tar.gz" sha
  sha=$(awk -v f="$file" '{ sub(/\r$/, "") } $2 == f { print $1; exit }' "$checksums")
  [[ "$sha" =~ ^[0-9a-f]{64}$ ]] || die "no valid checksum for $file in $checksums"
  printf '      url "https://github.com/quarto-dev/q2/releases/download/v%s/%s"\n' "$version" "$file"
  printf '      sha256 "%s"\n' "$sha"
}

darwin_arm64=$(archive darwin_arm64)
darwin_amd64=$(archive darwin_amd64)
linux_arm64=$(archive linux_arm64)
linux_amd64=$(archive linux_amd64)

cat <<EOF
# Generated by scripts/homebrew-formula.sh in quarto-dev/q2. Do not edit.
class Q2 < Formula
  desc "Quarto 2: scientific and technical publishing system"
  homepage "https://github.com/quarto-dev/q2"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
${darwin_arm64}
    end
    on_intel do
${darwin_amd64}
    end
  end

  on_linux do
    on_arm do
${linux_arm64}
    end
    on_intel do
${linux_amd64}
    end
  end

  def install
    bin.install "q2"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/q2 --version")
  end
end
EOF
